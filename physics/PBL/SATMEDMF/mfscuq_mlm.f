!>\file mfscuq_mlm.f
!!
!! This file contains downdraft parcel properties
!! parameterization for stratocumulus-top-driven turbulence based
!! on a Mixed-Layer-Model (MLM) following Solomon et al. 2026.

      module mfscuq_mlm_mod
      contains

!>\ingroup satmedmfvdifq
!! This subroutine computes downdraft parcel properties
!! for stratocumulus-top-driven turbulence using a
!! Mixed-Layer-Model (MLM) following Solomon et al. 2026
!! \section mfscuq GFS mfscu General Algorithm
!> @{
      subroutine mfscuq_mlm(im,ix,km,ntcw,ntsw,ntiw,
     &   nqni,ntrac1,cnvflg,zl,zm,q1,t1,u1,v1,
     &   prec,rad,buop,pres,liwse,mse,thlvx,
     &   radmin, cldtop, krad,              
     &   uflux,vflux,tdt,du,dv,rtg,
     &   eflux,rflux,wflux,pflux)
!
      use mo_pbl_kind, only : wp
      use machine,  only : kind_phys
      use physcons, grav => con_g, cp => con_cp,
     &              hvap => con_hvap, hfus => con_hfus
!
      implicit none
!
!  Dummy arguments
!
!  Dimensions and tracer indices
      integer, intent(in) :: im, ix, km
      integer, intent(in) :: ntcw, ntsw, ntiw
      integer, intent(in) :: nqni, ntrac1
!
!  Column flag; may be disabled by MLM
      logical, intent(inout) :: cnvflg(im)
!
!  Atmospheric state
      real(kind=kind_phys), intent(in) :: q1(ix,km,ntrac1)
      real(kind=kind_phys), intent(in) :: t1(ix,km)
      real(kind=kind_phys), intent(in) :: u1(ix,km)
      real(kind=kind_phys), intent(in) :: v1(ix,km)
!
!  Vertical coordinates and input diagnostics
      real(kind=kind_phys), intent(in) :: zl(im,km)
      real(kind=kind_phys), intent(in) :: zm(im,km)
      real(kind=wp),        intent(in) :: prec(im,km)
      real(kind=wp),        intent(in) :: rad(im,km)
      real(kind=kind_phys), intent(in) :: pres(im,km)
      real(kind=kind_phys), intent(in) :: liwse(im,km)
      real(kind=wp),        intent(in) :: mse(im,km)
      real(kind=kind_phys), intent(in) :: thlvx(im,km)
      real(kind=kind_phys), intent(in) :: radmin(im)
      integer, intent(in) :: cldtop(im)
      integer, intent(in) :: krad(im)
!
!  Buoyancy flux is read on entry and updated by MLM
      real(kind=wp), intent(inout) :: buop(im,km)
!
!  Existing tendencies are incremented/modified by MLM
      real(kind=wp),        intent(inout) :: tdt(im,km)
      real(kind=wp),        intent(inout) :: du(im,km)
      real(kind=wp),        intent(inout) :: dv(im,km)
      real(kind=kind_phys), intent(inout) :: rtg(im,km,ntrac1)
!
!  Internal turbulence fluxes generated by MLM (working precision)
      real(kind=wp),        intent(out) :: uflux(im,km)
      real(kind=wp),        intent(out) :: vflux(im,km)

!  CCPP Diagnostic fluxes (Host interface precision)
      real(kind=kind_phys), intent(out) :: eflux(im,km)
      real(kind=kind_phys), intent(out) :: rflux(im,km)
      real(kind=kind_phys), intent(out) :: wflux(im,km)
      real(kind=kind_phys), intent(out) :: pflux(im,km)
!
!  Local variables and arrays
!
      integer :: i, k, klim, icycle
      integer :: cldbase(im), mlmb(im), mlmt(im)
!
      logical :: totflg, flg(im)
!
      integer :: levs
      real(kind=wp) :: dz
      real(kind=wp) :: hflux(im,km)
      real(kind=wp) :: qflux(im,km)

      real(kind=wp) :: g, T0, elocp, slocp
      real(kind=wp) :: ts1, es1, qs1, ts2, es2, qs2
      real(kind=wp) :: alphaX, wezm, wezp
!
      real(kind=wp) :: b(im,km), qtx(im,km)
      real(kind=wp) :: dmse(im,km), dliwse(im,km)
      real(kind=wp) :: qcflux(im,km), qvflux(im,km)
      real(kind=wp) :: tflux(im,km), qsflux(im,km)
      real(kind=wp) :: bflux(im,km), qiflux(im,km)
      real(kind=wp) :: qniflux(im,km), qsnow(im,km)
      real(kind=wp) :: qice(im,km), qcloud(im,km), qnice(im,km)
      real(kind=wp) :: buopa(im)
!
      real(kind=wp) :: v_mean(im), u_mean(im)
      real(kind=wp) :: qi_mean(im), qs_mean(im), qni_mean(im)
      real(kind=wp) :: qtx_mean(im), mse_mean(im)
      real(kind=wp) :: dqsdT(im), dsvt(im), dsvb(im)
      real(kind=wp) :: em(im), ep(im), wm(im), wp_flx(im)
      real(kind=wp) :: dlb(im), dlt(im)
!
      real(kind=wp) :: C0,C1,C2,C3,C4,C5,C6,C7,C8,xtime
!
!  Physical parameters
      parameter(g     = real(grav, kind=wp))
      parameter(elocp = real(hvap, kind=wp) / real(cp, kind=wp))
      parameter(slocp = real(hfus, kind=wp) / real(cp, kind=wp))
      parameter(T0    = 273.15_wp)
      parameter(C0    = 6.11239921_wp)
      parameter(C1    = 0.443987641_wp)
      parameter(C2    = 0.142986287e-1_wp)
      parameter(C3    = 0.264847430e-3_wp)
      parameter(C4    = 0.302950461e-5_wp)
      parameter(C5    = 0.206739458e-7_wp)
      parameter(C6    = 0.640689451e-10_wp)
      parameter(C7    = -0.952447341e-13_wp)
      parameter(C8    = -0.976195544e-15_wp)
      parameter(xtime = 1800.0_wp)
      parameter(klim  = 3)

!************************************************************************
!
      ! Initialize output fluxes before potential early return
      uflux = 0.0_wp
      vflux = 0.0_wp
      eflux = 0.0_kind_phys
      rflux = 0.0_kind_phys
      wflux = 0.0_kind_phys
      pflux = 0.0_kind_phys
      
      totflg = .true.
      do i=1,im
         totflg = totflg .and. (.not. cnvflg(i))
      enddo
      if (totflg) return      
      
      do k=1,km
         do i=1,im
            qvflux(i,k) = 0.0_wp
            qcflux(i,k) = 0.0_wp
            qsflux(i,k) = 0.0_wp
            qiflux(i,k) = 0.0_wp
            qniflux(i,k) = 0.0_wp
            tflux(i,k)  = 0.0_wp
            uflux(i,k)  = 0.0_wp
            vflux(i,k)  = 0.0_wp
            bflux(i,k)  = 0.0_wp
            eflux(i,k)  = 0.0_kind_phys
            wflux(i,k)  = 0.0_kind_phys
            hflux(i,k)  = 0.0_wp
            qflux(i,k)  = 0.0_wp
            rflux(i,k)  = 0.0_kind_phys
            pflux(i,k)  = 0.0_kind_phys
            dmse(i,k)   = 0.0_wp
         enddo
      enddo

! Assume that cloud water and cloud ice are present
      do k=1,km
         do i=1,im
            qcloud(i,k) = real(q1(i,k,ntcw), kind=wp)
            qice(i,k)   = real(q1(i,k,ntiw), kind=wp)
            qsnow(i,k)  = 0.0_wp
            qnice(i,k)  = 0.0_wp
            qtx(i,k)    = real(q1(i,k,1), kind=wp) + qcloud(i,k)
     &                  + qice(i,k)
           if (k.gt.1.and.k.lt.km) bflux(i,k) = buop(i,k)*T0/g
         enddo
      enddo

      ! Test for existence of snow and ice number conc.
      if (ntsw.gt.0) then
        do k=1,km
           do i=1,im
             qsnow(i,k) = real(q1(i,k,ntsw), kind=wp)
             qtx(i,k)   = qtx(i,k)+qsnow(i,k)
           enddo
        enddo
      end if
      if (nqni.gt.0) then
        do k=1,km
           do i=1,im
             qnice(i,k) = real(q1(i,k,nqni), kind=wp)
           enddo
        enddo
      end if

      do i=1,im
         flg(i)     = .true.
         cldbase(i) = 1
         mlmb(i)    = 1
         mlmt(i)    = km-1
         dlb(i)     = 0.0_wp
         dlt(i)     = 0.0_wp
         buopa(i)   = 0.0_wp
      enddo

      do k = klim-1, km-2
         do i = 1, im
            dmse(i,k) = ((mse(i,k+1) - mse(i,k))
     &                / real(zm(i,k+1) - zm(i,k), kind=wp))
     &                / real(cp, kind=wp)
            dliwse(i,k) = ((real(liwse(i,k+1) - liwse(i,k), kind=wp))
     &                  / real(zm(i,k+1) - zm(i,k), kind=wp))
     &                  / real(cp, kind=wp)
            b(i,k) = real(t1(i,k), kind=wp)
     &             * (1.0_wp + 0.61_wp * real(q1(i,k,1), kind=wp)
     &             - qcloud(i,k) - qsnow(i,k) - qice(i,k))
         enddo
      enddo

      do i = 1, im
         if (cldtop(i).eq.km-1) cnvflg(i) = .false.
      enddo

      do k = km-1, klim,-1
         do i = 1, im
            if(cnvflg(i).and.qcloud(i,k).lt.1.0e-8_wp.and.k.lt.cldtop(i)
     &           .and.flg(i)) then
               cldbase(i) = k+1
               flg(i) = .false.
            endif
         enddo
      enddo

      do i = 1, im
         if (cldbase(i).eq.1)  cnvflg(i) = .false.
         if (cldbase(i).ge.cldtop(i)) cnvflg(i) = .false.
      enddo

      do i = 1, im
        flg(i)    = .true.
      enddo

      do i = 1, im
        if (cnvflg(i)) then
           mlmt(i)   = krad(i) - 2
           dlt(i)    = dmse(i,krad(i))
        endif
      enddo

      do i = 1, im
         if (radmin(i).ge.0.0_kind_phys) cnvflg(i) = .false.
         if (mlmt(i).eq.km-1)  cnvflg(i) = .false.
      enddo

      do i = 1, im
         if (cnvflg(i)) then
            mlmb(i) = mlmt(i) - 1
            flg(i)    = .true.
         endif
      enddo

!calculate mlm base; tunable parameter set to 0.005
      do k = km-1,  klim-1, -1
         do i = 1, im
            if (cnvflg(i).and.flg(i).and.k.lt.mlmt(i)-1.and.
     &           abs(dmse(i,k)).ge.0.005_wp) then
               mlmb(i) = k+1
               dlb(i) = dmse(i,k)
               flg(i) = .false.
            elseif (cnvflg(i).and.flg(i).and.k.eq.klim-1.and.
     &              abs(dmse(i,k)).lt.0.005_wp) then
               mlmb(i) = k+1
               dlb(i) = dmse(i,k)
               flg(i) = .false.
            endif
         enddo
      enddo

      do i = 1, im
         if (mlmb(i).eq.1)  cnvflg(i) = .false.
         if (mlmb(i).ge.mlmt(i)) cnvflg(i) = .false.
      enddo

      do i = 1, im
         u_mean(i)   = 0.0_wp
         v_mean(i)   = 0.0_wp
         qi_mean(i)  = 0.0_wp
         qs_mean(i)  = 0.0_wp
         qni_mean(i) = 0.0_wp
         mse_mean(i) = 0.0_wp
         qtx_mean(i) = 0.0_wp
      enddo

      do k = 1, km-1
         do i = 1, im
            if (k.ge.mlmb(i).and.k.le.mlmt(i)) then
               u_mean(i)   = u_mean(i)   + real(u1(i,k), kind=wp)
               v_mean(i)   = v_mean(i)   + real(v1(i,k), kind=wp)
               qi_mean(i)  = qi_mean(i)  + qice(i,k)
               qs_mean(i)  = qs_mean(i)  + qsnow(i,k)
               qni_mean(i) = qni_mean(i) + qnice(i,k)
               mse_mean(i) = mse_mean(i) + mse(i,k)
               qtx_mean(i) = qtx_mean(i) + qtx(i,k)
            endif
         enddo
      enddo

!mixed-layer mean values
      do i = 1, im
         levs = mlmt(i)-mlmb(i)+1
         u_mean(i)   = u_mean(i)/real(levs, kind=wp)
         v_mean(i)   = v_mean(i)/real(levs, kind=wp)
         qi_mean(i)  = qi_mean(i)/real(levs, kind=wp)
         qs_mean(i)  = qs_mean(i)/real(levs, kind=wp)
         qni_mean(i) = qni_mean(i)/real(levs, kind=wp)
         mse_mean(i) = mse_mean(i)/real(levs, kind=wp)
         qtx_mean(i) = qtx_mean(i)/real(levs, kind=wp)
      enddo

      do k = 1, km
         do i = 1, im
            uflux(i,k)   = 0.0_wp
            vflux(i,k)   = 0.0_wp
            qiflux(i,k)  = 0.0_wp
            qsflux(i,k)  = 0.0_wp
            qniflux(i,k) = 0.0_wp
         enddo
      enddo

!fields without equations damped to mixed-layer mean for now (1 hour damping)
      do k = 1, km
         do i = 1, im
            if (k.ge.mlmb(i).and.k.le.mlmt(i).and.cnvflg(i)) then
               dz = real(zm(i,k+1) - zm(i,k), kind=wp)
               uflux(i,k+1)   = uflux(i,k) + dz
     &                        * (real(u1(i,k), kind=wp) - u_mean(i))
     &                        / xtime
               vflux(i,k+1)   = vflux(i,k) + dz
     &                        * (real(v1(i,k), kind=wp) - v_mean(i))
     &                        / xtime
               qiflux(i,k+1)  = qiflux(i,k) + dz
     &                        * (qice(i,k) - qi_mean(i)) / xtime
               qsflux(i,k+1)  = qsflux(i,k) + dz
     &                        * (qsnow(i,k) - qs_mean(i)) / xtime
               qniflux(i,k+1) = qniflux(i,k) + dz
     &                        * (qnice(i,k) - qni_mean(i)) / xtime
            endif
         enddo
      enddo

      do i = 1, im
        if (cnvflg(i)) then
!water vapor at saturation in liquid layer
         ts1 = real(t1(i,cldbase(i)), kind=wp) - T0
         es1 = (C0 + ts1 * (C1 + ts1 * (C2 + ts1 * (C3 + ts1 * (C4
     &       + ts1 * (C5 + ts1 * (C6 + ts1 * (C7 + ts1 * C8))))))))
         qs1 = 0.622_wp * es1
     &       / (1.e-2_wp * real(pres(i,cldbase(i)), kind=wp) - es1)
         ts2 = real(t1(i,cldtop(i)), kind=wp) - T0
         es2 = (C0 + ts2 * (C1 + ts2 * (C2 + ts2 * (C3 + ts2 * (C4
     &       + ts2 * (C5 + ts2 * (C6 + ts2 * (C7 + ts2 * C8))))))))
         qs2 = 0.622_wp * es2
     &       / (1.e-2_wp * real(pres(i,cldtop(i)), kind=wp) - es2)
            dqsdT(i) = (qs2 - qs1) / (ts2 - ts1)
!added because dqsdT can be negative(?)
!        print*,'dqsdT ',dqsdT
         if (dqsdT(i) .lt. 5.0e-5_wp) dqsdT(i) = 5.0e-5_wp
         if (dqsdT(i) .gt. 1.0e-3_wp) dqsdT(i) = 1.0e-3_wp
        endif
      enddo

!need to cycle through to update bflux and entrainment velocities; tunable entrainment parameters
      do icycle = 1,3

         do i = 1, im
            buopa(i) = 0.0_wp
         enddo

         do k = 1, km
            do i = 1, im
               if (k.ge.mlmb(i).and.k.le.mlmt(i).and.cnvflg(i)) then
                buopa(i)=buopa(i)+2.5_wp*(zm(i,k+1)-zm(i,k))*bflux(i,k)
               endif
            enddo
         enddo

         do i = 1, im

            if (cnvflg(i)) then

               dsvb(i) = (b(i,mlmb(i)) - b(i,mlmb(i)-1))
     &                 * real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp)
               dsvt(i) = (b(i,mlmt(i)+1) - b(i,mlmt(i)))
     &                 * real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp)

               wezm = -0.2_wp * buopa(i) / dsvb(i)
               wezp =  0.2_wp * buopa(i) / dsvt(i)

               wezm = max(min(wezm,  0.005_wp), -0.02_wp)
               wezp = max(min(wezp,  0.005_wp), -0.001_wp)

               em(i) = rad(i,mlmb(i)+1) - wezm * (mse_mean(i)
     &               - mse(i,mlmb(i)-1)) / real(cp, kind=wp)
               ep(i) = rad(i,mlmt(i)+2) - wezp * (mse(i,mlmt(i)+1)
     &               - mse_mean(i)) / real(cp, kind=wp)
               wm(i) = prec(i,mlmb(i)+1) - wezm * (qtx_mean(i)
     &               - qtx(i,mlmb(i)-1))
               wp_flx(i) = prec(i,mlmt(i)+2) - wezp * (qtx(i,mlmt(i)+1)
     &                   - qtx_mean(i))

           endif
         enddo

         do k = 1, km
            do i = 1, im
               if (k.ge.mlmb(i).and.k.le.mlmt(i)+1.and.cnvflg(i)) then

!total energy and water fluxes are linear from mlmb to mlmt
                  rflux(i,k) = real(rad(i,k+1), kind=kind_phys)
                  pflux(i,k) = real(prec(i,k+1), kind=kind_phys)

                  eflux(i,k) = real(em(i) * (1.0_wp
     &                 - real(zm(i,k) - zm(i,mlmb(i)), kind=wp)
     &                 / real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp))
     &                 + ep(i) * real(zm(i,k) - zm(i,mlmb(i)), kind=wp)
     &                 / real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp),
     &                 kind=kind_phys)

                  wflux(i,k) = real(wm(i) * (1.0_wp
     &                 - real(zm(i,k) - zm(i,mlmb(i)), kind=wp)
     &                 / real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp))
     &                 + wp_flx(i)
     &                 * real(zm(i,k) - zm(i,mlmb(i)), kind=wp)
     &                 / real(zm(i,mlmt(i)+1) - zm(i,mlmb(i)), kind=wp),
     &                 kind=kind_phys)

!estimate fmse and qt fluxes from total water, total energy, precip, and radiation fluxes
                  hflux(i,k) = real(eflux(i,k) - rflux(i,k), kind=wp)
                  qflux(i,k) = real(wflux(i,k) - pflux(i,k), kind=wp)

!calculate fluxes below liquid layer (1.e-10 correct threshold?)
               if (qcloud(i,k).lt.1.e-10_wp) then

!frozen moist static energy and total water equations
              qvflux(i,k) = qflux(i,k)-qsflux(i,k)-qiflux(i,k)
              tflux(i,k)  = hflux(i,k)-elocp*qvflux(i,k)
     &             + slocp*qsflux(i,k) + slocp*qiflux(i,k)
              qcflux(i,k) = 0.0_wp

!calculate fluxes in liquid layer
               else
                  alphaX      = dqsdT(i)*elocp
!frozen moist static energy and total water equations
                  tflux(i,k)  = (hflux(i,k)+slocp*qsflux(i,k)
     &                 + slocp*qiflux(i,k))/(1.0_wp + alphaX)
                  qvflux(i,k) = dqsdT(i)*tflux(i,k)
                  qcflux(i,k) = qflux(i,k) - qvflux(i,k)
     &                 - qsflux(i,k) - qiflux(i,k)
               endif

!update buoyancy flux and pass out of routine
               bflux(i,k) = tflux(i,k) + T0*(0.61_wp*qvflux(i,k) -
     &              qcflux(i,k) - qsflux(i,k) - qiflux(i,k))
               buop(i,k)  = bflux(i,k)*g/T0

             endif !limit k
           enddo   !im
         enddo     !km
      enddo        !icycle

!     update tendencies
      do k = 1, km
         do i = 1, im
            if (k.ge.mlmb(i).and.k.le.mlmt(i).and.cnvflg(i)) then
            dz = real(zm(i,k+1) - zm(i,k), kind=wp)
            du(i,k)     = du(i,k)    - (uflux(i,k+1) -uflux(i,k))/dz
            dv(i,k)     = dv(i,k)    - (vflux(i,k+1) -vflux(i,k))/dz
            tdt(i,k)    = tdt(i,k)   - (tflux(i,k+1) -tflux(i,k))/dz
            rtg(i,k,1) = rtg(i,k,1) - real((qvflux(i,k+1) - qvflux(i,k))
     &                 / dz,kind=kind_phys)
            rtg(i,k,ntcw) = rtg(i,k,ntcw) - real((qcflux(i,k+1)
     &                    - qcflux(i,k)) / dz, kind=kind_phys)
            rtg(i,k,ntiw) = rtg(i,k,ntiw) - real((qiflux(i,k+1)
     &                    - qiflux(i,k)) / dz, kind=kind_phys)
            endif
         enddo
      enddo
      if (ntsw > 0) then
         do k = 1, km
            do i = 1, im
               if (k.ge.mlmb(i).and.k.le.mlmt(i).and.cnvflg(i)) then
                  dz = real(zm(i,k+1) - zm(i,k), kind=wp)
                  rtg(i,k,ntsw) = rtg(i,k,ntsw) - real(
     &                            (qsflux(i,k+1) - qsflux(i,k)) / dz,
     &                            kind=kind_phys)
               endif
            enddo
         enddo
      endif              
      if (nqni > 0) then
         do k = 1, km
            do i = 1, im
               if (k.ge.mlmb(i).and.k.le.mlmt(i).and.cnvflg(i)) then
                  dz = real(zm(i,k+1) - zm(i,k), kind=wp)
                  rtg(i,k,nqni) = rtg(i,k,nqni) - real(
     &                            (qniflux(i,k+1) - qniflux(i,k)) / dz,
     &                            kind=kind_phys)
               endif
            enddo
         enddo
      endif              

      do i=1,im
         if (cnvflg(i)) then
            k = mlmb(i)-1
            dz = zm(i,k+1)-zm(i,k)
            du(i,k)       = du(i,k)      - uflux(i,k+1)/dz
            dv(i,k)       = dv(i,k)      - vflux(i,k+1)/dz
            tdt(i,k)      = tdt(i,k)     - tflux(i,k+1)/dz
            rtg(i,k,1)    = rtg(i,k,1)
     &                    - real(qvflux(i,k+1) / dz, kind=kind_phys)
            rtg(i,k,ntcw) = rtg(i,k,ntcw)
     &                    - real(qcflux(i,k+1) / dz, kind=kind_phys)
            rtg(i,k,ntiw) = rtg(i,k,ntiw)
     &                    - real(qiflux(i,k+1) / dz, kind=kind_phys)

            if (ntsw > 0) then
              rtg(i,k,ntsw) = rtg(i,k,ntsw)
     &                      - real(qsflux(i,k+1) / dz, kind=kind_phys)
            endif
            if (nqni > 0) then
              rtg(i,k,nqni) = rtg(i,k,nqni)
     &                      - real(qniflux(i,k+1) / dz, kind=kind_phys)
            endif

            k = mlmt(i)+1
            dz = real(zm(i,k+1) - zm(i,k), kind=wp)
            du(i,k)       = du(i,k)       + uflux(i,k)/dz
            dv(i,k)       = dv(i,k)       + vflux(i,k)/dz
            tdt(i,k)      = tdt(i,k)      + tflux(i,k)/dz
            rtg(i,k,1)    = rtg(i,k,1)
     &                    + real(qvflux(i,k) / dz, kind=kind_phys)
            rtg(i,k,ntcw) = rtg(i,k,ntcw)
     &                    + real(qcflux(i,k) / dz, kind=kind_phys)
            rtg(i,k,ntiw) = rtg(i,k,ntiw)
     &                    + real(qiflux(i,k) / dz, kind=kind_phys)
                 
            if (ntsw > 0) then
              rtg(i,k,ntsw) = rtg(i,k,ntsw)
     &                      + real(qsflux(i,k) / dz, kind=kind_phys)
            endif
            if (nqni > 0) then
              rtg(i,k,nqni) = rtg(i,k,nqni)
     &                      + real(qniflux(i,k) / dz, kind=kind_phys)
            endif

!smooth discontinuity at cloud liquid base
            if (cldbase(i).gt.2) then
               k = cldbase(i)
               tdt(i,k-1)      = 0.5_wp * (tdt(i,k) + tdt(i,k-2))
               rtg(i,k-1,1)    = 0.5_kind_phys * (rtg(i,k,1)
     &                         + rtg(i,k-2,1))
               rtg(i,k-1,ntcw) = 0.5_kind_phys * (rtg(i,k,ntcw)
     &                         + rtg(i,k-2,ntcw))
            endif
         endif
      enddo

      return
      end
